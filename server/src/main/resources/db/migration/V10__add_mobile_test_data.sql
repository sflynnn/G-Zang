       COUNT(t.id) as transaction_count,
       COALESCE(SUM(CASE WHEN t.type=1 THEN t.amount ELSE 0 END), 0) as total_income,
       COALESCE(SUM(CASE WHEN t.type=2 THEN t.amount ELSE 0 END), 0) as total_expense
FROM t_book b
LEFT JOIN t_transaction t ON b.id = t.book_id
WHERE b.user_id = 1
GROUP BY b.id;

SELECT '=== 账户余额 ===' as '';
SELECT account_name, account_type, balance FROM t_account WHERE user_id = 1;

SELECT '=== 交易汇总 ===' as '';
SELECT
    COUNT(*) as total_transactions,
    SUM(CASE WHEN type=1 THEN amount ELSE 0 END) as total_income,
    SUM(CASE WHEN type=2 THEN amount ELSE 0 END) as total_expense,
    SUM(CASE WHEN type=1 THEN amount ELSE -amount END) as net_amount
FROM t_transaction WHERE user_id = 1;

SELECT '=== 月度趋势 ===' as '';
SELECT
    DATE_FORMAT(transaction_time, '%Y-%m') as month,
    SUM(CASE WHEN type=1 THEN amount ELSE 0 END) as income,
    SUM(CASE WHEN type=2 THEN amount ELSE 0 END) as expense
FROM t_transaction
WHERE user_id = 1
GROUP BY DATE_FORMAT(transaction_time, '%Y-%m')
ORDER BY month;

